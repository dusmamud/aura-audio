import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/home/hatch/.cache/ms-playwright/chromium-1208/chrome-linux64/chrome', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const errs = [];
page.on('pageerror', e => errs.push('pageerror: ' + e.message));
page.on('console', m => { if (m.type() === 'error') errs.push('console: ' + m.text()); });
page.on('requestfailed', r => errs.push('reqfail: ' + r.url()));
await page.goto('http://127.0.0.1:4321/', { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
const checks = {};
checks.announcement = await page.evaluate(() => document.querySelector('#announcement-text')?.textContent);
checks.navLinks = await page.evaluate(() => [...document.querySelectorAll('header nav a')].map(a => a.getAttribute('href')));
await page.click('#search-btn');
await page.waitForTimeout(400);
checks.searchVisible = await page.evaluate(() => !document.querySelector('#search-overlay').classList.contains('hidden'));
await page.fill('#search-input', 'buds');
await page.waitForTimeout(300);
checks.searchResults = await page.evaluate(() => document.querySelectorAll('#search-results li').length);
await page.keyboard.press('Escape');
await page.waitForTimeout(300);
await page.click('#bag-btn');
await page.waitForTimeout(500);
checks.drawerOpen = await page.evaluate(() => !document.querySelector('#cart-drawer').classList.contains('translate-x-full'));
checks.drawerEmpty = await page.evaluate(() => !document.querySelector('#cart-empty').classList.contains('hidden'));
checks.bagBadgeHidden = await page.evaluate(() => document.querySelector('#bag-count').classList.contains('hidden'));
await page.keyboard.press('Escape');
await page.waitForTimeout(300);
checks.drawerClosed = await page.evaluate(() => document.querySelector('#cart-drawer').classList.contains('translate-x-full'));
checks.overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth);
console.log(JSON.stringify(checks, null, 1));
console.log('ERRORS:', errs.length ? errs : 'none');
await browser.close();
